const express = require("express");
const c = require("./sale.controller");
const returns = require("./return.controller");
const requireAuth = require("../../middlewares/require-auth");
const r = express.Router();
r.use(requireAuth);
r.get("/", c.list);
r.get("/report", c.report);
r.post("/", c.create);
r.get("/:id", c.get);
r.get("/:id/items", c.items);
r.post("/:id/items", c.add);
r.post("/:id/complete", c.complete);
r.post("/:saleId/returns", returns.create);
r.get("/returns/:returnId", returns.get);
r.get("/returns/:returnId/items", returns.items);
r.post("/returns/:returnId/items", returns.add);
r.post("/returns/:returnId/complete", returns.complete);
module.exports = r;
